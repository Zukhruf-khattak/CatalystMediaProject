from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field

from app.schemas.retrieval import MemoryEvidenceItem, TranscriptEvidenceItem


class AgentCitationItem(BaseModel):
    """Verbatim quotation and meeting attribution supporting an agent claim."""

    meeting_id: str = Field(..., description="AMI meeting identifier (e.g. TS3006b)")
    quote: str = Field(..., description="Verbatim transcript quote supporting the claim")
    speaker_label: Optional[str] = Field(None, description="Speaker identifier (e.g. Speaker B)")
    speaker_role: Optional[str] = Field(
        None, description="Functional role (e.g. Industrial Designer)"
    )
    turn_id: Optional[str] = Field(None, description="UUID string of the source transcript turn")
    turn_index: Optional[int] = Field(
        None, description="Zero-based index within the meeting transcript"
    )


class CitationValidationItem(BaseModel):
    """Deterministic verification result for an individual citation."""

    is_valid: bool = Field(..., description="Whether the citation passed all individual checks")
    meeting_id: str = Field(..., description="AMI meeting identifier verified")
    quote: str = Field(..., description="Quotation text verified")
    word_count: int = Field(..., description="Word count in quote (must be >= 6)")
    speaker_label: Optional[str] = Field(None, description="Speaker label verified")
    turn_id: Optional[str] = Field(None, description="Source turn ID verified")
    errors: List[str] = Field(default_factory=list, description="Specific check failure messages")


class AnswerValidationResult(BaseModel):
    """Complete answer-level and citation validation result."""

    is_valid: bool = Field(..., description="Whether the answer and citations satisfy all rules")
    sentence_count: int = Field(..., description="Number of sentences in answer")
    citation_count: int = Field(..., description="Number of citations attached")
    distinct_meetings: List[str] = Field(
        default_factory=list, description="Distinct meeting codes cited"
    )
    supporting_meetings: List[str] = Field(
        default_factory=list, description="Meetings passing all validation"
    )
    citations: List[CitationValidationItem] = Field(
        default_factory=list, description="Per-citation validation results"
    )
    errors: List[str] = Field(default_factory=list, description="All validation error descriptions")


class AgentQueryRequest(BaseModel):
    """Inbound question payload submitted to the LangGraph agent."""

    question: str = Field(
        ...,
        min_length=3,
        description="Natural language question requiring cross-meeting intelligence",
        examples=["Why did Team TS3006 decide against fruit and vegetable shapes for the remote?"],
    )
    team_code: Optional[str] = Field(
        None,
        description="Optional team filter code (e.g. TS3006)",
        examples=["TS3006"],
    )
    session_id: Optional[str] = Field(
        None,
        description="Optional conversation/session UUID to resume prior context",
    )
    max_iterations: int = Field(
        2,
        ge=1,
        le=5,
        description="Maximum retrieval loop iterations before halting",
    )


class AgentQueryResponse(BaseModel):
    """Outbound evidence-grounded response generated by the LangGraph agent."""

    question: str = Field(..., description="Original input question")
    answer: str = Field(..., description="Synthesized, evidence-grounded 1-3 sentence answer")
    is_sufficient: bool = Field(..., description="True if evidence was sufficient to answer")
    insufficient_reason: Optional[str] = Field(
        None, description="Explanation if evidence was insufficient"
    )
    citations: List[AgentCitationItem] = Field(
        default_factory=list,
        description="Exact transcript quotations backing the answer",
    )
    supporting_turns: List[TranscriptEvidenceItem] = Field(
        default_factory=list,
        description="Source transcript segments retrieved during execution",
    )
    supporting_memories: List[MemoryEvidenceItem] = Field(
        default_factory=list,
        description="Temporal memories and relationship chains retrieved",
    )
    steps_taken: List[str] = Field(
        default_factory=list,
        description="Ordered sequence of LangGraph nodes executed",
    )
    session_id: str = Field(..., description="Session identifier for thread resumption")
    iteration_count: int = Field(1, description="Number of retrieval loops performed")
    team_code: Optional[str] = Field(None, description="Associated team code")
    validation_status: str = Field(
        "PASSED",
        description="Deterministic citation and evidence validation outcome: PASSED, FAILED, or SKIPPED",
    )
    validation_errors: List[str] = Field(
        default_factory=list,
        description="Deterministic validation error descriptions if any check failed",
    )
    supporting_meetings: List[str] = Field(
        default_factory=list,
        description="Unique meeting codes that contributed verified citations",
    )
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of response creation",
    )


class AgentStatusResponse(BaseModel):
    """Health and configuration metadata for the LangGraph agent."""

    status: str = Field("operational", description="Current operational status")
    model_provider: str = Field(..., description="Active LLM provider class or backend")
    model_name: str = Field(..., description="Model identifier configured")
    tools_available: List[str] = Field(
        default_factory=list,
        description="List of registered agent tools",
    )
    checkpointer: str = Field(..., description="Session checkpointing engine")
    langsmith_tracing: bool = Field(..., description="Whether LangSmith tracing is active")


class AgentSessionDetailResponse(BaseModel):
    """Full detail view of an agent conversation session."""

    session_id: str = Field(..., description="Unique session identifier")
    team_code: Optional[str] = Field(None, description="Associated team code")
    title: Optional[str] = Field(None, description="Session summary or first question")
    turn_count: int = Field(0, description="Total queries answered in this session")
    history: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of question-answer interactions in this session",
    )
    created_at: datetime = Field(..., description="Session creation timestamp")
    updated_at: datetime = Field(..., description="Session last updated timestamp")
